package ru.agimate.controlapi.database.enums;

/**
 * Статус модели в реестре {@code llm_provider_models} — свежесть по последнему успешному
 * discovery-листингу провайдера, НЕ рантайм-истина (листинги бывают неполными, часть
 * OpenAI-совместимых бэкендов {@code /models} не реализует). Advisory: показывается в UI
 * (бейдж на биндинге агента), но LLM-вызовы по нему не блокируются — authority на «модель
 * жива» остаётся за провайдером в момент вызова.
 */
public enum LlmProviderModelStatus {

    /** Модель присутствовала в последнем успешном листинге провайдера. */
    AVAILABLE,

    /** Модель пропала из листинга (или ни разу в нём не встречалась — {@code first_seen_at} null). */
    UNAVAILABLE
}
